/** 内核问题与运行故障的参数（Ask.params、Run.fault.params）：只有机制值与对象名。 */
export type NoticeParams = Record<string, string> | undefined;
/** 内核生成的问题（设计 §6.3）：按类别码与参数说一句人话；技术细节（params.detail、问题原文）收在「详情」里。 */
type AskSay = Record<I.AskCode, (p: NoticeParams) => string>;
/** 运行故障（设计 §6.11）：出了什么事一句（say），下一步做什么一句（next）。 */
type FaultSay = Record<I.RunFault, { say: (p: NoticeParams) => string; next: string }>;
/** go：下一步去哪修（按钮文字与地址）；没有时下一步就是看这件事。 */
type NoticeSay = Record<I.NoticeCode, { say: (p: NoticeParams) => string; go?: { label: string; to: string } }>;
const mins = (p: NoticeParams) => Math.max(1, Math.round(Number(p?.timeout ?? 0) / 60));

/** 自检结论的可变参数（kernel/doctor 的 data，附录 B.2）。 */
export type DoctorData = Record<string, unknown> | undefined;
/** 自检结论（设计 §15.5）：按机器码与 data 生成一句话。封闭集合：DOCTOR_CODE 多一个而这里没写，tsc 失败。 */
type DoctorSay = Record<I.DoctorCode, (d: DoctorData) => string>;
const num = (d: DoctorData, k: string) => Number(d?.[k] ?? 0);
// draft_schema 的 data.shape：端点返回的内容长什么样（kernel/outcall/model 的 Shape*）。
const DRAFT_SHAPE_ZH: Record<string, string> = {
  empty: "：返回为空", markdown_fence: "：被代码块包着", truncated: "：被截断", malformed_json: "：不是合法 JSON",
  trailing_data: "：JSON 后多了内容", text_around: "：JSON 前后夹着文字", plain_text: "：返回的是一段文字",
  no_tool_call: "：没有调用输出工具",
};
const DRAFT_SHAPE_EN: Record<string, string> = {
  empty: ": empty reply", markdown_fence: ": wrapped in a code block", truncated: ": cut off", malformed_json: ": not valid JSON",
  trailing_data: ": extra text after the JSON", text_around: ": text around the JSON", plain_text: ": plain text, no JSON",
  no_tool_call: ": the output tool was not called",
};
// 这些形态说明端点没守结构化约束：提示换协议。
const IGNORED_SHAPES = new Set(["markdown_fence", "text_around", "plain_text", "no_tool_call"]);
const ignored = (d: DoctorData) => IGNORED_SHAPES.has(String(d?.shape));
const stamp = (loc: string) => (d: DoctorData, k: string) => {
  const v = d?.[k];
  return typeof v === "string" && !v.startsWith("0001") && v !== "never" ? new Date(v).toLocaleString(loc) : "";
};
const at = stamp("zh-CN"), atEn = stamp("en");
const len = (d: DoctorData, k: string) => (Array.isArray(d?.[k]) ? (d![k] as unknown[]).length : 0);

